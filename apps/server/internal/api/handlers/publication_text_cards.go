// Shared by REST and MCP, including handlers constructed for individual calls.
var textCardPreviewLimiter = ratelimit.New()

func (h *PublicationHandler) SetTextCardStorage(storage mediastore.BlobStorage) {
	if storage != nil {
		h.textCards = publicationcards.New(h.db, storage, h.entitlement)
	}
}

type PreviewTextCardInput struct {
	Body struct {
		SocialAccountID string         `json:"social_account_id" doc:"Connected account whose name, handle and profile photo appear on the card"`
		Text            string         `json:"text" maxLength:"2200" doc:"Effective destination text"`
		OutputProfile   string         `json:"output_profile,omitempty" doc:"Provider format, including instagram.story for a vertical Story"`
		AttachmentCount int            `json:"attachment_count,omitempty" minimum:"0" maximum:"35" doc:"Following attachments; adds a next-slide arrow"`
		Settings        map[string]any `json:"settings,omitempty" doc:"Text card style settings, also accepted in rendition and Social Set defaults"`
	}
}

type TextCardPreviewImage struct {
	DataURL string `json:"data_url" doc:"Private JPEG preview generated by the publishing renderer"`
	Width   int    `json:"width"`
	Height  int    `json:"height"`
}

type PreviewTextCardOutput struct {
	CacheControl string `header:"Cache-Control"`
	Body         struct {
		Images []TextCardPreviewImage `json:"images"`
	}
}

func (h *PublicationHandler) previewTextCard(api huma.API) {
	huma.Register(api, huma.Operation{OperationID: "preview-text-card", Method: http.MethodPost, Path: "/publications/preview-text-card", Summary: "Preview text as publishing images", Tags: []string{tagPublications}, MaxBodyBytes: 32 * 1024, Middlewares: huma.Middlewares{middleware.AuthMiddleware(api, h.auth)}, Errors: []int{400, 403, 404, 429, 503}}, h.renderTextCardPreview)
}

func (h *PublicationHandler) renderTextCardPreview(ctx context.Context, input *PreviewTextCardInput) (*PreviewTextCardOutput, error) {
	return h.previewTextCardForUser(ctx, middleware.GetUserID(ctx), input)
}

func (h *PublicationHandler) previewTextCardForUser(ctx context.Context, userID string, input *PreviewTextCardInput) (*PreviewTextCardOutput, error) {
	var account models.SocialAccount
	if err := h.db.NewSelect().Model(&account).Where("id = ?", input.Body.SocialAccountID).Scan(ctx); err != nil {
		return nil, huma.Error404NotFound("Account not found")
	}
	if err := h.checkWorkspaceAccess(ctx, account.WorkspaceID, userID); err != nil {
		return nil, err
	}
	if _, err := h.loadAccounts(ctx, account.WorkspaceID, []string{account.ID}); err != nil {
		return nil, err
	}
	if input.Body.AttachmentCount < 0 || input.Body.AttachmentCount > 35 {
		return nil, huma.Error400BadRequest("Invalid attachment count")
	}
	if !textcards.Supported(account.Platform, input.Body.OutputProfile) {
		return nil, huma.Error400BadRequest("This format does not support text cards")
	}
	style, err := textcards.Parse(input.Body.Settings)
	if err != nil {
		return nil, huma.Error400BadRequest(err.Error())
	}
	if h.textCards == nil {
		return nil, huma.Error503ServiceUnavailable("Text card rendering is unavailable")
	}
	if !textCardPreviewLimiter.Allow("text-card-preview:"+userID, 30, time.Minute) {
		return nil, huma.Error429TooManyRequests("Text card previews are rate limited; try again shortly")
	}
	images, err := h.textCards.Preview(ctx, account, input.Body.Text, input.Body.OutputProfile, style, input.Body.AttachmentCount)
	if errors.Is(err, publicationcards.ErrRenderBusy) {
		return nil, huma.Error429TooManyRequests("Text card rendering is busy; try again shortly")
	}
	if err != nil {
		return nil, huma.Error400BadRequest(err.Error())
	}
	output := &PreviewTextCardOutput{CacheControl: "private, no-store"}
	for _, img := range images {
		output.Body.Images = append(output.Body.Images, TextCardPreviewImage{DataURL: "data:image/jpeg;base64," + base64.StdEncoding.EncodeToString(img.JPEG), Width: img.Width, Height: img.Height})
	}
	return output, nil
}

func (h *PublicationHandler) refreshPublicationTextCards(ctx context.Context, db bun.Tx, publicationID string, resolveFormats bool, previousIDs ...string) error {
	if h.textCards == nil {
		return nil
	}
	var publication models.Publication
	if err := db.NewSelect().Model(&publication).Where("id = ?", publicationID).Scan(ctx); err != nil {
		return err
	}
	canonical, sourceInputs, err := h.loadCanonicalSegmentInputsWithDB(ctx, db, publicationID)
	if err != nil {
		return err
	}
	var renditions []models.Rendition
	if err := db.NewSelect().Model(&renditions).Where("publication_id = ?", publicationID).Scan(ctx); err != nil {
		return err
	}
	for _, rendition := range renditions {
		if !textcards.Supported(rendition.Platform, "") {
			continue
		}
		if !textCardSettingsEnabled(rendition.SettingsJSON) {
			continue
		}
		if err := h.refreshTextCardRendition(ctx, db, publication, rendition, canonical, sourceInputs, resolveFormats); err != nil {
			return err
		}
	}
	return h.textCards.Finalize(ctx, db, publication.WorkspaceID, previousIDs)
}

func publicationTextCardIDs(publication PublicationResponse) []string {
	var ids []string
	for _, rendition := range publication.Renditions {
		for _, segment := range rendition.Segments {
			for _, media := range segment.OutputMedia {
				if media.Role == textcards.MediaRole {
					ids = append(ids, media.ID)
				}
			}
		}
	}
	return ids
}

func cardSegmentIDs(segments []models.RenditionSegment) []string {
	ids := make([]string, len(segments))
	for i, segment := range segments {
		ids[i] = segment.ID
	}
	return ids
}

func refreshTextCardInheritedMedia(ctx context.Context, db bun.IDB, segment *models.RenditionSegment, sources []PublicationSegmentInput, joined bool) error {
	if _, err := db.NewDelete().Model((*models.RenditionSegmentMedia)(nil)).Where("rendition_segment_id = ? AND role != ?", segment.ID, textcards.MediaRole).Exec(ctx); err != nil {
		return err
	}
	seen := map[string]bool{}
	for _, source := range sources {
		if !joined && source.ID != segment.PublicationSegmentID {
			continue
		}
		for _, media := range source.Media {
			if seen[media.MediaID] {
				continue
			}
			row := models.RenditionSegmentMedia{RenditionSegmentID: segment.ID, MediaID: media.MediaID, Role: publicationFirstNonEmpty(media.Role, "attachment"), DisplayOrder: len(seen), AltText: media.AltText, SettingsJSON: mustJSON(media.Settings), ThumbnailTimestampMS: media.ThumbnailTimestampMS}
			seen[media.MediaID] = true
			if _, err := db.NewInsert().Model(&row).Exec(ctx); err != nil {
				return err
			}
		}
	}
	return nil
}

func authoredPublicationMedia(media []MediaSummary) []MediaSummary {
	result := make([]MediaSummary, 0, len(media))
	for _, item := range media {
		if item.Role != textcards.MediaRole {
			result = append(result, item)
		}
	}
	return result
}

func validateAuthoredMediaRoles(media []PublicationMediaInput) error {
	for _, item := range media {
		if item.Role == textcards.MediaRole {
			return huma.Error400BadRequest("text_card is a generated media role. Configure text_card in destination settings instead.")
		}
	}
	return nil
}

func textCardSettingsEnabled(settingsJSON string) bool {
	var settings map[string]any
	_ = json.Unmarshal([]byte(settingsJSON), &settings)
	mode, _ := settings["text_card"].(string)
	return strings.TrimSpace(mode) != "" && mode != "off"
}

// Only a newly added destination receives the creation default. Missing settings
// on an existing destination remain off, including older scheduled publications.
func (h *PublicationHandler) defaultNewTextCardDestinations(ctx context.Context, db bun.IDB, publicationID string, inputs []RenditionInput, accounts map[string]models.SocialAccount) error {
	if h.textCards == nil {
		return nil
	}
	var existing []models.Rendition
	if err := db.NewSelect().Model(&existing).Where("publication_id = ?", publicationID).Scan(ctx); err != nil {
		return err
	}
	for i := range inputs {
		found := false
		for _, rendition := range existing {
			if rendition.SocialAccountID == inputs[i].SocialAccountID {
				found = true
				break
			}
		}
		if !found {
			inputs[i].Settings = textcards.NewPostDefaults(accounts[inputs[i].SocialAccountID].Platform, inputs[i].Settings)
		}
	}
	return nil
}

// Explicit source versions become one output while retaining their independent
// inheritance choices in the canonical source-overrides representation.
func joinTextCardSources(input RenditionInput, canonical []models.PublicationSegment, sources []PublicationSegmentInput) (RenditionSegmentInput, error) {
	joined := input.Segments[0]
	joined.PublicationSegmentID = canonical[0].ID
	joined.SourceOverrides = nil
	for position, segment := range input.Segments {
		if len(segment.SourceOverrides) > 0 {
			return joined, huma.Error400BadRequest("A joined text card accepts one source_overrides list")
		}
		if mustJSON(segment.Settings) != mustJSON(joined.Settings) {
			return joined, huma.Error400BadRequest("Joined text cards require the same destination segment settings")
		}
		source := canonicalPublicationSegment(position, segment.PublicationSegmentID, canonical, sources)
		if source.ID == "" {
			return joined, huma.Error400BadRequest("Text card source does not match the publication")
		}
		bodyOverride, _ := renditionTextOverride(segment.BodyOverride, segment.Body, source.Body)
		var canonicalMedia []PublicationMediaInput
		for _, candidate := range sources {
			if candidate.ID == source.ID {
				canonicalMedia = candidate.Media
				break
			}
		}
		mediaInherited := len(segment.Media) == 0 || publicationMediaInputsEqual(segment.Media, canonicalMedia)
		if segment.MediaInherited != nil {
			mediaInherited = *segment.MediaInherited
		}
		joined.SourceOverrides = append(joined.SourceOverrides, publicationsource.RenditionSourceOverride{PublicationSegmentID: source.ID, BodyOverride: bodyOverride, MediaInherited: mediaInherited, Media: segment.Media})
	}
	return normalizeJoinedSourceOverrides(joined, canonical, sources)
}

func validateTextCardOutput(rendition models.Rendition, segment RenditionSegmentResponse, settings map[string]any) []capabilities.ValidationIssue {
	style, err := textcards.Parse(settings)
	if err != nil || !style.Applies(rendition.Platform, rendition.OutputProfile, segment.Body, len(segment.Media)) {
		return nil
	}
	pages, err := textcards.Layout(segment.Body, rendition.OutputProfile)
	message := ""
	if err != nil {
		message = err.Error()
	} else {
		cards := 0
		for _, media := range segment.OutputMedia {
			if media.Role == textcards.MediaRole {
				cards++
			}
		}
		if cards != len(pages) {
			message = "Save this post again to generate its publishing images."
		}
	}
	if message == "" {
		return nil
	}
	return []capabilities.ValidationIssue{{Severity: "error", Code: "text_card_unavailable", Message: message, FallbackMessage: message, Provider: rendition.Platform, OutputProfile: rendition.OutputProfile, SegmentID: segment.ID, Scope: capabilities.SettingScopeSegment, ScopeID: segment.ID, Field: "text_card"}}
}

func (h *PublicationHandler) refreshTextCardRendition(ctx context.Context, db bun.IDB, publication models.Publication, rendition models.Rendition, canonical []models.PublicationSegment, sourceInputs []PublicationSegmentInput, resolveFormats bool) error {
	var account models.SocialAccount
	if err := db.NewSelect().Model(&account).Where("id = ?", rendition.SocialAccountID).Scan(ctx); err != nil {
		return err
	}
	var settings map[string]any
	_ = json.Unmarshal([]byte(rendition.SettingsJSON), &settings)
	var segments []models.RenditionSegment
	if err := db.NewSelect().Model(&segments).Where("rendition_id = ?", rendition.ID).Order("position ASC").Scan(ctx); err != nil {
		return err
	}
	if err := refreshTextCardSources(ctx, db, rendition, segments, canonical, sourceInputs); err != nil {
		return err
	}
	if resolveFormats && !rendition.FormatLocked {
		var inputs []capabilities.ResolveSegment
		media, err := h.loadRenditionSegmentMediaWithDB(ctx, db, cardSegmentIDs(segments))
		if err != nil {
			return err
		}
		for _, segment := range segments {
			inputs = append(inputs, capabilities.ResolveSegment{ID: segment.ID, Body: segment.Body, Media: capabilityMediaFromSummaries(authoredPublicationMedia(media[segment.ID]))})
		}
		resolved := capabilities.Resolve(account.Platform, capabilities.ResolveInput{Segments: inputs, Settings: settings, CreationPreset: publication.CreationPreset, Intent: publication.Intent})
		rendition.Profile, rendition.OutputProfile = resolved.Profile, resolved.OutputProfile
		if _, err := db.NewUpdate().Model(&rendition).Column("profile", "output_profile").Where("id = ?", rendition.ID).Exec(ctx); err != nil {
			return err
		}
	}
	for _, segment := range segments {
		var overrides map[string]any
		_ = json.Unmarshal([]byte(segment.SettingsJSON), &overrides)
		if err := h.textCards.RefreshSegment(ctx, db, account, rendition, segment, mergePublicationSettings(settings, overrides)); err != nil {
			if errors.Is(err, publicationcards.ErrRenderBusy) {
				return huma.Error429TooManyRequests("Text card rendering is busy; try again shortly")
			}
			return huma.Error400BadRequest("Could not create the text card: " + err.Error())
		}
	}
	return refreshRenditionMediaProjection(ctx, db, rendition.ID)
}

func refreshTextCardSources(ctx context.Context, db bun.IDB, rendition models.Rendition, segments []models.RenditionSegment, canonical []models.PublicationSegment, sourceInputs []PublicationSegmentInput) error {
	for i := range segments {
		segment := &segments[i]
		for _, source := range canonical {
			if source.ID != segment.PublicationSegmentID {
				continue
			}
			joined := len(segments) == 1 && len(canonical) > 1
			refreshPollSegment(segment, rendition, source, canonical, nil, joined)
			if _, err := db.NewUpdate().Model(segment).Column("body", "settings_json").Where("id = ?", segment.ID).Exec(ctx); err != nil {
				return err
			}
			if segment.MediaInherited && !publicationsource.HasSourceOverrides(segment.SourceOverridesJSON) {
				if err := refreshTextCardInheritedMedia(ctx, db, segment, sourceInputs, joined); err != nil {
					return err
				}
			}
			break
		}
	}
	return nil
}

func deliveredSegmentMedia(segment RenditionSegmentResponse) []MediaSummary {
	if segment.OutputMedia != nil {
		return segment.OutputMedia
	}
	return segment.Media
}
